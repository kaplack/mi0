// One local end-to-end scenario, with an isolated PostgreSQL schema.
const path = require('node:path');
const fs = require('node:fs/promises');
const { pathToFileURL } = require('node:url');
const assert = require('node:assert/strict');
const { chromium } = require('../../web/node_modules/@playwright/test');
const { isolatedDatabase } = require('../citas/test-helpers');
(async () => {
  let isolated, server, vite, browser;
  try {
    isolated = await isolatedDatabase();
    process.env.CORS_ORIGIN = 'http://localhost:5176';
    server = await new Promise(resolve => { const appServer = require('../app').listen(0, '127.0.0.1', () => resolve(appServer)); });
    const api = 'http://127.0.0.1:' + server.address().port;
    process.env.VITE_API_URL = api;
    const { createServer } = await import(pathToFileURL(require.resolve('../../web/node_modules/vite/dist/node/index.js')).href);
    const root = path.resolve(__dirname, '../../web');
    vite = await createServer({ root, configFile: path.join(root, 'vite.config.js'), server: { host: 'localhost', port: 5176, strictPort: true } });
    await vite.listen();
    browser = await chromium.launch({ channel: 'chrome', headless: true });
    const errors = [];
    const original = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    const manager = await original.newPage(); manager.on('pageerror', e => errors.push(e.message));
    manager.on('dialog', dialog => dialog.accept());
    await manager.goto('http://localhost:5176/mi-bingo');
    await manager.getByLabel('Nombre del evento').fill('Bingo libre v1.1');
    await manager.getByRole('button', { name: 'Crear bingo gratis', exact: true }).click();
    await manager.getByRole('heading', { name: 'Bingo libre v1.1', exact: true }).waitFor();
    const stored = await manager.evaluate(() => JSON.parse(localStorage.getItem('mi0_bingo_guest')));
    const code = stored.code;
    const output = path.resolve(__dirname, '../../web/test-results/bingo'); await fs.mkdir(output, { recursive: true });
    await manager.screenshot({ path: path.join(output, 'guest-desktop.png'), fullPage: true });
    await manager.reload();
    await manager.getByRole('heading', { name: 'Bingo libre v1.1', exact: true }).waitFor();
    const playerContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
    const player = await playerContext.newPage(); player.on('pageerror', e => errors.push(e.message));
    await player.goto('http://localhost:5176/bingo/' + code);
    await player.getByLabel('Tu nombre').fill('Jugador de prueba');
    await player.getByRole('button', { name: 'Recibir mi cartón' }).click();
    await player.getByRole('button', { name: 'Centro libre' }).waitFor();
    await manager.locator('.bingo-guest-access').getByText('Participantes: 1 / 30', { exact: true }).waitFor();
    await manager.getByRole('button', { name: 'Iniciar nueva ronda' }).click();
    await manager.getByRole('button', { name: 'Sacar bolilla' }).click();
    await manager.getByText('1 de 75 bolillas', { exact: true }).waitFor();
    const before = await isolated.db.bingoRoom.findUnique({ where: { code }, include: { participants: true, rounds: true } });
    await manager.getByText('Guardar acceso de recuperación', { exact: true }).click();
    await manager.getByRole('button', { name: 'Generar enlace privado', exact: true }).click();
    await manager.getByLabel('Enlace privado', { exact: true }).waitFor();
    const recoveryLink = await manager.getByLabel('Enlace privado', { exact: true }).inputValue();
    assert.ok(recoveryLink.includes('#recuperar='));
    const recoveredContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
    const recovered = await recoveredContext.newPage(); recovered.on('pageerror', e => errors.push(e.message));
    const recoverySecret = recoveryLink.split('.').at(-1);
    const leaked = []; recovered.on('request', request => { const url = new URL(request.url()); if ((url.origin + url.pathname + url.search).includes(recoverySecret)) leaked.push(url.pathname); });
    await recovered.goto(recoveryLink);
    await recovered.getByRole('heading', { name: 'Bingo libre v1.1', exact: true }).waitFor();
    assert.equal(new URL(recovered.url()).hash, ''); assert.deepEqual(leaked, []);
    await recovered.getByText('1 de 75 bolillas', { exact: true }).waitFor();
    assert.ok(await recovered.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await recovered.screenshot({ path: path.join(output, 'recovered-mobile.png'), fullPage: true });
    const denied = await fetch(api + '/api/bingo/guest/' + code + '/info', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ adminToken: stored.adminToken }) });
    assert.equal(denied.status, 403);
    await recovered.getByText('¿Necesitas más cartones? Amplía a 50 gratis', { exact: true }).click();
    await recovered.getByRole('button', { name: 'Ampliar a 50 gratis', exact: true }).click();
    await recovered.getByLabel('Nombre', { exact: true }).fill('Organizador');
    await recovered.getByLabel('Apellido', { exact: true }).fill('Prueba');
    await recovered.getByLabel('Correo', { exact: true }).fill('bingo-ui-' + Date.now() + '@test.invalid');
    await recovered.getByLabel('Contraseña', { exact: true }).fill('test-password-1234');
    await recovered.getByRole('button', { name: 'Crear cuenta', exact: true }).click();
    await recovered.getByRole('button', { name: 'Vincular esta sala y ampliar a 50', exact: true }).click();
    await recovered.getByRole('heading', { name: 'Bingo libre v1.1', exact: true }).waitFor();
    await recovered.getByRole('heading', { name: 'Participantes: 1 / 50', exact: true }).waitFor();
    assert.ok(!recovered.url().includes('#'));
    const after = await isolated.db.bingoRoom.findUnique({ where: { code }, include: { participants: true, rounds: true } });
    assert.equal(after.id, before.id); assert.equal(after.guestId, null); assert.equal(after.participantLimit, 50);
    assert.deepEqual(after.participants, before.participants); assert.deepEqual(after.rounds, before.rounds);
    await player.reload(); await player.getByRole('button', { name: 'Centro libre' }).waitFor();
    await recovered.screenshot({ path: path.join(output, 'registered-mobile.png'), fullPage: true });
    assert.deepEqual(errors, []);
    console.log('UI v1.1 correcta: creación, recarga, recuperación privada en otro contexto, revocación, registro y retorno al mismo bingo con 50 cartones.');
  } finally {
    if (browser) await browser.close();
    if (vite) await vite.close();
    if (server) await new Promise(resolve => server.close(resolve));
    if (isolated) await isolated.cleanup();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
